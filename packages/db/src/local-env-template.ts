/**
 * Values are written unquoted into the generated .env.local file, so each
 * value must be dotenv-safe: no whitespace, `#`, quotes, or `$`. The
 * generator in scripts/init-local-env.ts sources these from hex and base64
 * output, which is always safe.
 */
export interface LocalEnvSecrets {
  readonly osUser: string;
  readonly appPassword: string;
  readonly staffPassword: string;
  readonly publicPassword: string;
  /** The CMS role, which owns Payload's database. */
  readonly cmsPassword: string;
  /** Shared by both apps: a staff session must verify the same way in the console and the dashboard. */
  readonly authSecret: string;
  /** Shared with the website repository, which sends Get started enquiries to /api/leads with it. */
  readonly leadsApiToken: string;
  /** Payload's own signing secret. Both apps open the same CMS database, so both need it. */
  readonly payloadSecret: string;
}

const DATABASE_HOST = "localhost:5432";
export const DEV_DATABASE = "brandbasket_platform";
export const TEST_DATABASE = "brandbasket_platform_test";
/** Payload keeps its own database and manages its own schema; nothing in packages/db migrates it. */
export const PAYLOAD_DATABASE = "brandbasket_platform_payload";

function ownerUrl(osUser: string, database: string): string {
  return `postgresql://${encodeURIComponent(osUser)}@${DATABASE_HOST}/${database}`;
}

function roleUrl(role: string, password: string, database: string): string {
  return `postgresql://${role}:${encodeURIComponent(password)}@${DATABASE_HOST}/${database}`;
}

/** The website runs from its own repository (brandbasket-website) on port 3130. */
const WEBSITE_URL = "http://localhost:3130";
const APP_URL = "http://app.brandbasket.localhost:3198";
/** The staff console is its own Next app on its own port; it is not served by the platform any more. */
const ADMIN_URL = "http://console.brandbasket.localhost:3199";
const TEAM_EMAIL = "team@example.com";

/** Contents of apps/platform/.env.local for local development: the customer app, scripts and tests. */
export function buildLocalEnvFile(secrets: LocalEnvSecrets): string {
  return [
    "# Local development only. Generated by `pnpm env:init`. Never commit this file.",
    "",
    "# Migrations and role setup connect as your local Postgres superuser.",
    `DATABASE_URL_OWNER=${ownerUrl(secrets.osUser, DEV_DATABASE)}`,
    `DATABASE_URL_OWNER_TEST=${ownerUrl(secrets.osUser, TEST_DATABASE)}`,
    "",
    "# Passwords for the application roles created by `pnpm db:roles`.",
    `BRANDBASKET_APP_PASSWORD=${secrets.appPassword}`,
    `BRANDBASKET_STAFF_PASSWORD=${secrets.staffPassword}`,
    `BRANDBASKET_PUBLIC_PASSWORD=${secrets.publicPassword}`,
    `BRANDBASKET_CMS_PASSWORD=${secrets.cmsPassword}`,
    "",
    "# Runtime connections. bb_app is bound by row-level security; bb_staff does staff and system work.",
    `DATABASE_URL=${roleUrl("bb_app", secrets.appPassword, DEV_DATABASE)}`,
    `DATABASE_URL_STAFF=${roleUrl("bb_staff", secrets.staffPassword, DEV_DATABASE)}`,
    `DATABASE_URL_TEST=${roleUrl("bb_app", secrets.appPassword, TEST_DATABASE)}`,
    `DATABASE_URL_STAFF_TEST=${roleUrl("bb_staff", secrets.staffPassword, TEST_DATABASE)}`,
    `DATABASE_URL_PUBLIC=${roleUrl("bb_public", secrets.publicPassword, DEV_DATABASE)}`,
    `DATABASE_URL_PUBLIC_TEST=${roleUrl("bb_public", secrets.publicPassword, TEST_DATABASE)}`,
    "",
    "# Auth",
    `BETTER_AUTH_SECRET=${secrets.authSecret}`,
    "",
    "# Payload CMS. Its own database, owned by bb_cms, which it migrates itself.",
    `DATABASE_URL_PAYLOAD=${roleUrl("bb_cms", secrets.cmsPassword, PAYLOAD_DATABASE)}`,
    `PAYLOAD_SECRET=${secrets.payloadSecret}`,
    "",
    "# Enquiries from the website (POST /api/leads). Copy this token into the website's .env.local.",
    `LEADS_API_TOKEN=${secrets.leadsApiToken}`,
    `BRANDBASKET_TEAM_EMAIL=${TEAM_EMAIL}`,
    "",
    "# Public values (inlined into the browser bundle).",
    `NEXT_PUBLIC_SITE_URL=${WEBSITE_URL}`,
    `NEXT_PUBLIC_APP_URL=${APP_URL}`,
    "",
    "# Hosts. Chrome and Firefox resolve *.localhost to this machine.",
    `APP_ORIGIN=${APP_URL}`,
    `ADMIN_ORIGIN=${ADMIN_URL}`,
    "",
  ].join("\n");
}

/**
 * Contents of apps/admin/.env.local: the staff console, which is its own Next app since the split.
 *
 * Narrower than the platform's on purpose. It gets the staff connection, the CMS and the shared auth secret, and
 * none of the customer or lead-intake credentials — see apps/admin/lib/server/env.ts for why.
 */
export function buildAdminEnvFile(secrets: LocalEnvSecrets): string {
  return [
    "# Local development only. Generated by `pnpm env:init`. Never commit this file.",
    "",
    "# Staff and system work. No DATABASE_URL and no DATABASE_URL_PUBLIC: the console has no use for either.",
    `DATABASE_URL_STAFF=${roleUrl("bb_staff", secrets.staffPassword, DEV_DATABASE)}`,
    "",
    "# Payload CMS, the same database the platform reads blog posts from.",
    `DATABASE_URL_PAYLOAD=${roleUrl("bb_cms", secrets.cmsPassword, PAYLOAD_DATABASE)}`,
    `PAYLOAD_SECRET=${secrets.payloadSecret}`,
    "",
    "# Must match the platform's, so a staff session verifies the same way in both apps.",
    `BETTER_AUTH_SECRET=${secrets.authSecret}`,
    "",
    "# Hosts. APP_ORIGIN is the customer app: setup links staff send point there, not here.",
    `ADMIN_ORIGIN=${ADMIN_URL}`,
    `APP_ORIGIN=${APP_URL}`,
    "",
  ].join("\n");
}
