import type { CollectionConfig } from "payload";

/**
 * One document per Fynix business (packages/db's `businesses` table is the source of truth for identity;
 * `businessId` here is that table's id, kept in sync automatically when a business is created — see
 * apps/platform/lib/server/payload-tenant-sync.ts, called from every place a business row is created). Never
 * created by hand in the Payload admin panel: staff pick an existing tenant from the switcher, they don't make new
 * ones here.
 */
export const Tenants: CollectionConfig = {
  slug: "tenants",
  admin: {
    useAsTitle: "name",
  },
  access: {
    // Denies everything by default, on purpose (corrected 2026-09-18, spec review — see collections/Media.ts's
    // doc comment for the full incident writeup). Every legitimate caller is our own trusted server code, using
    // the Local API with `overrideAccess: true` — a Local-API-only parameter no REST or GraphQL request can set —
    // so a request that reaches this collection through Payload's own REST/GraphQL API must be refused outright,
    // not just routed away by `requireAdminHost`'s Host-header check. The comment this replaced claimed "every
    // authenticated Payload user may read/manage tenants" as if that were a real restriction; it wasn't — nobody
    // ever authenticates to Payload itself, so `req.user` is always empty and that check never actually held
    // anyone back.
    read: () => false,
    create: () => false,
    update: () => false,
    delete: () => false, // a business is never deleted this way; removing a tenant is a deliberate, separate decision
  },
  fields: [
    {
      name: "businessId",
      type: "text",
      required: true,
      unique: true,
      admin: { description: "Matches packages/db's businesses.id. Set automatically — do not edit by hand." },
    },
    {
      name: "name",
      type: "text",
      required: true,
    },
    {
      name: "siteApiToken",
      type: "text",
      index: true,
      admin: {
        description:
          "Bearer token this business's own website uses to read its published blog posts. Generated by staff " +
          "from the client page; rotating it breaks the client site until the new value is deployed there.",
      },
    },
  ],
};
