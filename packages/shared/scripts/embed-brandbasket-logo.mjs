// Writes src/server/brandbasket-letterhead.ts: the Soft bB logo for light backgrounds as a base64 PNG, for the letterhead
// of tax invoices and receipts. A PNG because the logo's SVG uses a mask, which pdf-lib's drawSvgPath cannot draw.
// Run after the logo changes: copy brand/web-assets/brandbasket-logo-horizontal-light.png into assets/, then
// node packages/shared/scripts/embed-brandbasket-logo.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bytes = readFileSync(join(root, "assets", "brandbasket-logo-horizontal-light.png"));
if (bytes.subarray(1, 4).toString("latin1") !== "PNG") throw new Error("brandbasket-logo-horizontal-light.png is not a PNG");
// The IHDR chunk holds the pixel size: width and height as big-endian 32-bit integers at bytes 16 and 20.
const width = bytes.readUInt32BE(16);
const height = bytes.readUInt32BE(20);

const out = [
  "// Generated by scripts/embed-brandbasket-logo.mjs from assets/brandbasket-logo-horizontal-light.png. Do not edit.",
  "",
  "/**",
  " * The Brandbasket logo (Soft bB, horizontal, for light backgrounds, transparent) as a base64 PNG, for the letterhead of a",
  " * tax invoice or receipt. `width` and `height` are its pixels, so a caller can keep the proportions.",
  " */",
  "export const BRANDBASKET_LETTERHEAD: { readonly png: string; readonly width: number; readonly height: number } = {",
  `  png: "${bytes.toString("base64")}",`,
  `  width: ${width},`,
  `  height: ${height},`,
  "};",
];
writeFileSync(join(root, "src", "server", "brandbasket-letterhead.ts"), `${out.join("\n")}\n`);
console.log("wrote src/server/brandbasket-letterhead.ts");
