#!/usr/bin/env bash
# What this does: writes the two production environment files, /srv/fynix/shared/platform.env.local and admin.env.local,
# from the database passwords in /root/fynix-secrets.env (made by setup-database.sh) and freshly generated secrets, with the
# values only a person can supply (Brevo and Razorpay keys) left blank, marked, for you to fill in.
#
# What it assumes: run as root on the droplet after setup-database.sh. It NEVER overwrites a file that already exists
# (so re-running is safe and cannot lose a key you filled in); it prints what it skipped. Dry-run by default; --apply writes.
# The files are created mode 600, owned by the deploy user. The secrets that must match in both files are generated once and
# written to both. Afterwards run `pnpm env:check` (or deploy.sh does) to see what is still blank.
#
# Hostnames: FYNIX_APP_HOST (default app.fynix.digital) and FYNIX_ADMIN_HOST (default console.fynix.digital).
# Test hooks: FYNIX_ROOT, FYNIX_SECRETS_FILE, FYNIX_DEPLOY_USER (default deploy), FYNIX_PG_HOST (default localhost).
set -euo pipefail

APPLY=0
for arg in "$@"; do
  case "$arg" in
    --apply) APPLY=1 ;;
    -h | --help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg (try --help)" >&2; exit 64 ;;
  esac
done

ROOT="${FYNIX_ROOT:-/srv/fynix}"
SECRETS_FILE="${FYNIX_SECRETS_FILE:-/root/fynix-secrets.env}"
DEPLOY_USER="${FYNIX_DEPLOY_USER:-deploy}"
PG_HOST="${FYNIX_PG_HOST:-localhost}"
APP_URL="https://${FYNIX_APP_HOST:-app.fynix.digital}"
STAFF_URL="https://${FYNIX_ADMIN_HOST:-console.fynix.digital}"
SHARED="$ROOT/shared"
PLATFORM_FILE="$SHARED/platform.env.local"
ADMIN_FILE="$SHARED/admin.env.local"

say() { printf '%s\n' "$*"; }
secret() { grep -E "^$1=" "$SECRETS_FILE" | head -n 1 | cut -d= -f2-; }

if [[ ! -f "$SECRETS_FILE" ]]; then say "No $SECRETS_FILE: run setup-database.sh --apply first." >&2; exit 1; fi
APP_PW="$(secret APP_PW)"; STAFF_PW="$(secret STAFF_PW)"; PUBLIC_PW="$(secret PUBLIC_PW)"; CMS_PW="$(secret CMS_PW)"
for pair in "APP_PW=$APP_PW" "STAFF_PW=$STAFF_PW" "PUBLIC_PW=$PUBLIC_PW" "CMS_PW=$CMS_PW"; do
  if [[ -z "${pair#*=}" ]]; then say "${pair%%=*} is missing from $SECRETS_FILE: run setup-database.sh --apply." >&2; exit 1; fi
done

if [[ -e "$PLATFORM_FILE" && -e "$ADMIN_FILE" ]]; then
  say "Both files already exist; nothing to do."; say "  $PLATFORM_FILE"; say "  $ADMIN_FILE"; exit 0
fi
if [[ -e "$PLATFORM_FILE" || -e "$ADMIN_FILE" ]]; then
  say "Only one of the two files exists. Refusing to guess which secrets the other must match." >&2
  say "Remove neither: copy BETTER_AUTH_SECRET and PAYLOAD_SECRET from the one that exists into a new one by hand." >&2
  exit 1
fi

if [[ $APPLY -eq 0 ]]; then
  say "[dry-run] would write $PLATFORM_FILE and $ADMIN_FILE (mode 600, owner $DEPLOY_USER), with new secrets and database URLs from $SECRETS_FILE."
  say "[dry-run] run again with --apply."
  exit 0
fi

BETTER_AUTH_SECRET="$(openssl rand -hex 32)"
PAYLOAD_SECRET="$(openssl rand -hex 32)"
ACCOUNT_CODE_SECRET="$(openssl rand -hex 32)"
RAZORPAY_WEBHOOK_SECRET="$(openssl rand -hex 32)"
ACCOUNT_ERASE_TOKEN="$(openssl rand -hex 32)"

mkdir -p "$SHARED"
( umask 077
  cat >"$PLATFORM_FILE" <<PLATFORM
# Fynix dashboard (apps/platform). Generated by make-env-files.sh. Mode 600. Every variable is explained in
# apps/platform/.env.production.example. Fill the three FILL_ME lines, then run: pnpm env:check
APP_ORIGIN=$APP_URL
ADMIN_ORIGIN=$STAFF_URL
NEXT_PUBLIC_APP_URL=$APP_URL

DATABASE_URL=postgresql://fynix_app:$APP_PW@$PG_HOST:5432/fynix_platform
DATABASE_URL_STAFF=postgresql://fynix_staff:$STAFF_PW@$PG_HOST:5432/fynix_platform
DATABASE_URL_PUBLIC=postgresql://fynix_public:$PUBLIC_PW@$PG_HOST:5432/fynix_platform
DATABASE_URL_PAYLOAD=postgresql://fynix_cms:$CMS_PW@$PG_HOST:5432/fynix_platform_payload

# The same two secrets are in the console's file. Never change one without the other.
BETTER_AUTH_SECRET=$BETTER_AUTH_SECRET
PAYLOAD_SECRET=$PAYLOAD_SECRET
ACCOUNT_CODE_SECRET=$ACCOUNT_CODE_SECRET
ACCOUNT_ERASE_TOKEN=$ACCOUNT_ERASE_TOKEN

# FILL_ME: Brevo API key (v3), after the fynix.digital domain is authenticated in Brevo.
BREVO_API_KEY=
FYNIX_MAIL_FROM=no-reply@fynix.digital

BILLING_PROVIDER=razorpay
# FILL_ME: Razorpay keys (rzp_test_ first, rzp_live_ at go-live). The same pair is in the console's file.
RAZORPAY_KEY_ID=
RAZORPAY_KEY_SECRET=
# Enter this same value in Razorpay's dashboard when you create the webhook, at the same moment.
RAZORPAY_WEBHOOK_SECRET=$RAZORPAY_WEBHOOK_SECRET

# Uploads and private support screenshots live on this machine, the same directories in both files, outside the releases.
FYNIX_MEDIA_ROOT=$ROOT/media
FYNIX_SUPPORT_ROOT=$ROOT/support-private

# Robot check (Cloudflare Turnstile): fill both to turn it on.
TURNSTILE_SITE_KEY=
TURNSTILE_SECRET=
PLATFORM
  cat >"$ADMIN_FILE" <<ADMIN
# Fynix staff console (apps/admin). Generated by make-env-files.sh. Mode 600. Every variable is explained in
# apps/admin/.env.production.example. Fill the FILL_ME lines (the same values as the dashboard's), then run: pnpm env:check
APP_ORIGIN=$APP_URL
ADMIN_ORIGIN=$STAFF_URL

DATABASE_URL_STAFF=postgresql://fynix_staff:$STAFF_PW@$PG_HOST:5432/fynix_platform
DATABASE_URL_PAYLOAD=postgresql://fynix_cms:$CMS_PW@$PG_HOST:5432/fynix_platform_payload

# Identical to the dashboard's file.
BETTER_AUTH_SECRET=$BETTER_AUTH_SECRET
PAYLOAD_SECRET=$PAYLOAD_SECRET

# FILL_ME: the same Brevo key as the dashboard's.
BREVO_API_KEY=
FYNIX_MAIL_FROM=no-reply@fynix.digital

BILLING_PROVIDER=razorpay
# FILL_ME: the same Razorpay key pair as the dashboard's (the Pricing page creates the Razorpay plans with it).
RAZORPAY_KEY_ID=
RAZORPAY_KEY_SECRET=

FYNIX_MEDIA_ROOT=$ROOT/media
FYNIX_SUPPORT_ROOT=$ROOT/support-private

TURNSTILE_SITE_KEY=
TURNSTILE_SECRET=
ADMIN
)
chmod 600 "$PLATFORM_FILE" "$ADMIN_FILE"
if id "$DEPLOY_USER" >/dev/null 2>&1; then chown "$DEPLOY_USER":"$DEPLOY_USER" "$PLATFORM_FILE" "$ADMIN_FILE" 2>/dev/null || true; fi
say "Wrote $PLATFORM_FILE and $ADMIN_FILE (mode 600)."
say "Now fill BREVO_API_KEY, RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET in BOTH files, then run: pnpm env:check --platform $PLATFORM_FILE --admin $ADMIN_FILE"
